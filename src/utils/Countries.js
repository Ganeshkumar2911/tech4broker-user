export const findCountryValue = (rawCountry) => {
  if (!rawCountry) return "";
  const str = String(rawCountry).trim();
  if (!str) return "";

  // 1. Direct match on value (e.g. 'IN')
  const valueMatch = countries.find(
    (c) => c.value.toUpperCase() === str.toUpperCase(),
  );
  if (valueMatch) return valueMatch.value;

  // 2. Match on name or label
  const nameMatch = countries.find(
    (c) =>
      (c.name && c.name.toUpperCase() === str.toUpperCase()) ||
      (c.label && c.label.toUpperCase() === str.toUpperCase()),
  );
  if (nameMatch) return nameMatch.value;

  // 3. Match code inside brackets like "India [IN]" or "(IN)" or "(🇮🇳 India)"
  const bracketMatch =
    str.match(/\[([A-Za-z]{2})\]/) || str.match(/\(([A-Za-z]{2})\)/);
  if (bracketMatch && bracketMatch[1]) {
    const code = bracketMatch[1].toUpperCase();
    const codeMatch = countries.find((c) => c.value.toUpperCase() === code);
    if (codeMatch) return codeMatch.value;
  }

  // 4. Match country name part
  const namePart = str
    .split("[")[0]
    .split("(")[0]
    .replace(/[^\w\s]/gi, "")
    .trim()
    .toUpperCase();
  if (namePart) {
    const matched = countries.find(
      (c) =>
        (c.name && c.name.toUpperCase().includes(namePart)) ||
        (c.label && c.label.toUpperCase().includes(namePart)),
    );
    if (matched) return matched.value;
  }

  return str;
};

export const getCountryPhoneCode = (rawCountry) => {
  if (!rawCountry) return "+91";
  const val = findCountryValue(rawCountry);
  const found = countries.find((c) => c.value === val);
  return found?.phoneCode || "+91";
};

export const getCountryDisplayLabel = (rawCountry) => {
  if (!rawCountry) return "Not set";
  const val = findCountryValue(rawCountry);
  const found = countries.find((c) => c.value === val);
  return found ? found.name || found.label : rawCountry;
};
